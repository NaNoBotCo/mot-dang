#!/usr/bin/env python3
"""Generate the front-page clock's lunation disc into assets/front/lunation.js.

Nan, 2026-10-12: "add the moon phase complication we built to the clock on
Motdang homepage. Should take up the face." The complication is the whole dial
at wichaa.net/moon (../manuscript-wiki/moondial.py): age ring, ดับ/เพ็ญ, beaded
bezel, milled case, the disc of two moons behind the cloud plate, the two
indices. This file draws nothing of its own. It cuts moondial.dial_svg() into
four layers at its own element boundaries, so the disc and the indices can turn
on a canvas, and the phase is moondial's own script (elongation series,
new-moon search, disc gear) cut out of DIAL_JS between two markers. Change the
dial there and regenerate here.

    python3 importers/make_lunation_js.py
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WIKI = os.path.join(os.path.dirname(ROOT), "manuscript-wiki")
# NOT docs/ — build.py wipes that directory every run; front_layer copies this in.
OUT = os.path.join(ROOT, "assets", "front", "lunation.js")

START = "  var D=Math.PI/180"
STOP = "  // How much of the crossing moon's disc"
SERIF = '"Sukhumvit Set","Noto Serif Thai",Thonburi,"Iowan Old Style",Palatino,Georgia,serif'


def build():
    sys.path.insert(0, WIKI)
    import moondial as M

    js = M.DIAL_JS
    ephem = js[js.index(START):js.index(STOP)].rstrip()

    # the dial's own text rules, so the age ring reads the same inside an image
    css = "".join(l.strip() for l in M.DIAL_CSS.splitlines()
                  if l.strip().startswith(".dial ")).replace("var(--serif)", SERIF)
    s = M.dial_svg().replace(M._kanok_corners(), "")
    s = s.replace("<svg viewBox='0 0 800 800'",
                  "<svg xmlns='http://www.w3.org/2000/svg' width='800' height='800' viewBox='0 0 800 800'", 1)
    s = re.sub(r"\s+", " ", s).replace("</defs>", "<style>" + css + "</style></defs>", 1)
    fill, _ = M._plate_silhouette()
    head = s[:s.index("</defs>") + len("</defs>")]
    i_disc = s.index("<g id='disc'")
    i_plate = s.index("<path d='%s'" % fill)
    i_index = s.index("<g id='index'")
    i_text = s.index("<text x=", i_index)
    tail = s[i_text:]
    layers = {
        "under": s[:i_disc] + "</g></svg>",                                  # case to sky; opened clip closed empty
        "disc": head + s[i_disc:i_plate].rstrip() + "</svg>",                # the disc group, unclipped
        "over": head + "<g clip-path='url(#ap)'>" + s[i_plate:i_index] + tail,   # plate, bezel, case, signature
        "index": head + s[i_index:i_text] + "</svg>",
    }
    geo = {"CX": M.CX, "CY": M.CY, "A": M.A, "DISC_CY": M.DISC_CY, "R": M.R_CASE_OUT}
    return f"""// The lunation disc on the front-page clock: wichaa.net/moon's dial, generated by
// importers/make_lunation_js.py from ../manuscript-wiki/moondial.py. Do not edit here.
// MDLUNA.gear(ms) is moondial's own gear; MDLUNA.draw(k, cx, cy, r, ms) draws the dial,
// its case filling a circle of radius r, with the disc and both indices turned to the phase.
(function (global) {{
  'use strict';
{ephem}

  var G = {json.dumps(geo)};
  var SVG = {json.dumps(layers)};
  var IMG = {{}}, left = 4;
  Object.keys(SVG).forEach(function (k) {{
    var im = new Image();
    im.onload = function () {{ if (--left === 0) {{ L.ready = true; document.dispatchEvent(new Event('mdluna')); }} }};
    im.src = 'data:image/svg+xml;charset=utf-8,' + encodeURIComponent(SVG[k]);
    IMG[k] = im;
  }});

  function draw(k, cx, cy, r, ms) {{
    if (!L.ready) return null;
    var g = gear(ms), s = r / G.R, b = (g.disc - 90) * D;
    k.save();
    k.translate(cx, cy); k.scale(s, s); k.translate(-G.CX, -G.CY);
    k.beginPath(); k.arc(G.CX, G.CY, G.R, 0, 6.2832); k.clip();
    k.drawImage(IMG.under, 0, 0, 800, 800);
    k.save();
    k.beginPath(); k.arc(G.CX, G.CY, G.A, 0, 6.2832); k.clip();
    k.translate(G.CX, G.CY + G.A * G.DISC_CY); k.rotate(b); k.translate(-G.CX, -(G.CY + G.A * G.DISC_CY));
    k.drawImage(IMG.disc, 0, 0, 800, 800);
    k.restore();
    k.drawImage(IMG.over, 0, 0, 800, 800);
    k.translate(G.CX, G.CY); k.rotate(b); k.translate(-G.CX, -G.CY);
    k.drawImage(IMG.index, 0, 0, 800, 800);
    k.restore();
    return g;
  }}

  var L = {{ ready: false, gear: gear, elong: elong, draw: draw }};
  global.MDLUNA = L;
}})(window);
"""


def main():
    out = build()
    with open(OUT, "w") as f:
        f.write(out)
    print("lunation.js: %d bytes" % len(out))


if __name__ == "__main__":
    main()
