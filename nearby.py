#!/usr/bin/env python3
"""near.js — the one distance function on this site, and the one locate button.

WO-57. /chuai.html and /foon.html both answer "what is nearest to me", and
the second one nearly shipped with its own copy of the haversine, its own
bilingual span builder and its own geolocation error strings. Two copies of
one fact is the failure this repo keeps finding — a rounded kilometre on one
page and a rounded metre on the other, or a permission refusal that speaks
Thai on one and English on the other. So both pages load this, and each
supplies only the part that is genuinely its own: how a row is drawn.

    MDNear.km(aLat,aLng,bLat,bLng)  great-circle kilometres
    MDNear.far(km)                  a distance a reader can hold, bilingual
    MDNear.bi(th,en)                the site's own bilingual pair, in JS
    MDNear.esc(text)                escape for innerHTML
    MDNear.locate(out, then)        the button's whole job: say what is
                                    happening, ask the device, hand back
                                    [lat,lng], and say so in both languages
                                    when it cannot. The position is passed to
                                    `then` and to nothing else — it is never
                                    stored and never sent.

Entry point: emit(DOCS) writes docs/near.js. Both layers call it; writing it
twice in one build is harmless and neither has to know which ran first.
"""

JS = """// near.js — generated by nearby.py. Shared by /chuai.html and /foon.html.
// The reader's position is handed to the page's own draw function and to
// nothing else: it is not stored, not put in the URL, and not sent anywhere.
window.MDNear=(function(){
function bi(th,en){return '<span class="bi"><span class="th" lang="th">'+th
 +'</span><span class="en" lang="en"><span class="th" lang="th"> \\u00B7 </span>'
 +en+'</span></span>';}
function esc(t){return String(t==null?'':t)
 .replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/"/g,'&quot;');}
function km(a,b,c,e){var R=6371,t=Math.PI/180,x=(c-a)*t,y=(e-b)*t;
var h=Math.sin(x/2)*Math.sin(x/2)+Math.cos(a*t)*Math.cos(c*t)
     *Math.sin(y/2)*Math.sin(y/2);
return 2*R*Math.asin(Math.sqrt(h));}
function far(k){return k<1?bi(Math.round(k*1000)+' \\u0E21.',Math.round(k*1000)+' m')
 :bi(k.toFixed(1)+' \\u0E01\\u0E21.',k.toFixed(1)+' km');}
function say(out,th,en){out.innerHTML='<p class="ch-none">'+bi(th,en)+'</p>';}
function locate(out,then){
 say(out,'\\u0E01\\u0E33\\u0E25\\u0E31\\u0E07\\u0E2B\\u0E32\\u2026','finding you\\u2026');
 if(!navigator.geolocation){
  say(out,'\\u0E40\\u0E04\\u0E23\\u0E37\\u0E48\\u0E2D\\u0E07\\u0E19\\u0E35\\u0E49\\u0E1A\\u0E2D\\u0E01\\u0E15\\u0E33\\u0E41\\u0E2B\\u0E19\\u0E48\\u0E07\\u0E44\\u0E21\\u0E48\\u0E44\\u0E14\\u0E49',
      'this device cannot give a position');return;}
 navigator.geolocation.getCurrentPosition(
  function(p){then([p.coords.latitude,p.coords.longitude]);},
  function(){say(out,'\\u0E44\\u0E21\\u0E48\\u0E44\\u0E14\\u0E49\\u0E15\\u0E33\\u0E41\\u0E2B\\u0E19\\u0E48\\u0E07','no position');},
  {enableHighAccuracy:true,timeout:12000,maximumAge:120000});}
// A pin a phone can act on: geo: opens whatever map the reader actually has.
function pin(la,ln){var a=la.toFixed(5),b=ln.toFixed(5);
 return '<a class="ch-rm" href="geo:'+a+','+b+'?q='+a+','+b+'" title="'+a+','+b
  +'">\\uD83D\\uDCCD</a>';}
// A number may be written with an extension — "053471274 \u0E15\u0E48\u0E2D 112".
// The href takes the dialable part; the label keeps what the place wrote,
// because the extension is how the reader reaches the right desk.
function tel(t){if(!t)return '';
 var m=String(t).match(/[+]?[0-9][0-9 ()\u2010-\u2015.-]*/);
 var href=m?m[0].replace(/[^+0-9]/g,''):'';
 if(href.length<6)return '<span class="ch-rt">\\u260E '+esc(t)+'</span>';
 return '<a class="ch-rt" href="tel:'+href+'">\\u260E '+esc(t)+'</a>';}
return {bi:bi,esc:esc,km:km,far:far,say:say,locate:locate,pin:pin,tel:tel};
})();
"""


def emit(docs):
    (docs / "near.js").write_text(JS)
    return "near.js"
